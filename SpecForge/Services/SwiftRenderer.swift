import Foundation

extension GeneratorContext {
    // MARK: - Public output assembly

    func makeResult() -> GenerationResult {
        let modelsFile = renderModelsFile()
        let clientFile = renderAPIClientFile()
        let endpointsFile = renderEndpointsFile()
        let jsonFile = usesJSONValue ? renderJSONValueFile() : nil

        let sourceRoot = options.includePackageManifest ? "Sources/\(packageName)/" : ""
        var files: [GeneratedFile] = []

        if options.includePackageManifest {
            files.append(GeneratedFile(
                path: "Package.swift",
                content: renderPackageManifest(),
                kind: .manifest
            ))
        }

        files.append(GeneratedFile(
            path: sourceRoot + "Models.swift",
            content: modelsFile,
            kind: .swift
        ))
        files.append(GeneratedFile(
            path: sourceRoot + "APIClient.swift",
            content: clientFile,
            kind: .swift
        ))
        if !operations.isEmpty {
            files.append(GeneratedFile(
                path: sourceRoot + "Endpoints.swift",
                content: endpointsFile,
                kind: .swift
            ))
        }
        if let jsonFile {
            files.append(GeneratedFile(
                path: sourceRoot + "JSONValue.swift",
                content: jsonFile,
                kind: .swift
            ))
        }
        if options.includeReadme {
            files.append(GeneratedFile(
                path: "README.md",
                content: renderReadme(sourceRoot: sourceRoot),
                kind: .markdown
            ))
        }

        let endpointSummaries = operations.map { operation in
            GeneratedEndpoint(
                method: operation.method,
                path: operation.path,
                functionName: operation.swiftName,
                summary: operation.summary,
                responseType: operation.response.swiftTypeName,
                tag: operation.tag
            )
        }

        return GenerationResult(
            files: files,
            endpoints: endpointSummaries,
            warnings: warnings,
            metadata: SpecMetadata(
                title: apiTitle,
                version: apiVersion,
                description: apiDescription,
                specificationVersion: specVersion.displayName,
                baseURL: baseURL,
                sourceLabel: sourceLabel,
                packageName: packageName
            ),
            modelCount: modelOrder.count,
            endpointCount: operations.count,
            packageName: packageName
        )
    }

    // MARK: - Files

    private var generatedHeader: String {
        let source = sourceLabel
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
        return """
        // \(apiTitle) — Swift API client
        // Generated by SpecForge from \(specVersion.displayName).
        // Source: \(source)
        //
        // This file is generated. Regenerate it when the API contract changes.
        """
    }

    private func renderModelsFile() -> String {
        let body: String
        if modelOrder.isEmpty {
            body = "// No named schemas were defined in this specification."
        } else {
            body = modelOrder.compactMap { name in
                models[name].map(renderModel)
            }.joined(separator: "\n\n")
        }
        return """
        \(generatedHeader)

        import Foundation

        \(body)
        """
    }

    private func renderModel(_ model: ModelDefinition) -> String {
        switch model.kind {
        case .object:
            return renderObjectModel(model)
        case .stringEnum, .intEnum:
            return renderEnumModel(model)
        case .union:
            return renderUnionModel(model)
        case .alias:
            return renderAliasModel(model)
        }
    }

    private func renderObjectModel(_ model: ModelDefinition) -> String {
        let properties = objectProperties(for: model.name)
        let access = effectiveAccessPrefix
        var blocks: [String] = []

        let documentation = SwiftNaming.commentLines(
            model.schema["description"]?.stringValue ?? "Generated model for \(model.name)."
        )
        blocks.append(documentation.joined(separator: "\n"))

        if model.isRecursive {
            blocks.append("\(access)final class \(model.name): Codable {")
        } else {
            blocks.append("\(access)struct \(model.name): Codable {")
        }

        var members: [String] = []
        for property in properties {
            var lines: [String] = []
            if property.isDeprecated {
                lines.append("@available(*, deprecated, message: \"Deprecated by the API specification.\")")
            }
            lines.append(contentsOf: SwiftNaming.commentLines(property.description))
            lines.append("\(access)var \(property.swiftName): \(property.declarationType)")
            members.append(lines.joined(separator: "\n"))
        }

        if needsCodingKeys(properties) {
            var codingLines = ["private enum CodingKeys: String, CodingKey {"]
            for property in properties {
                if unescaped(property.swiftName) == property.jsonKey {
                    codingLines.append("    case \(property.swiftName)")
                } else {
                    codingLines.append(
                        "    case \(property.swiftName) = \(SwiftNaming.stringLiteral(property.jsonKey))"
                    )
                }
            }
            codingLines.append("}")
            members.append(codingLines.joined(separator: "\n"))
        }

        let parameters = properties.map { property -> String in
            let defaultValue = property.isOptional ? " = nil" : ""
            return "\(property.swiftName): \(property.declarationType)\(defaultValue)"
        }
        var initializer = ["\(access)init(\(parameters.joined(separator: ", "))) {"]
        for property in properties {
            initializer.append("    self.\(property.swiftName) = \(property.swiftName)")
        }
        initializer.append("}")
        members.append(initializer.joined(separator: "\n"))

        blocks.append(SwiftNaming.indent(members.joined(separator: "\n\n")))
        blocks.append("}")
        return blocks.joined(separator: "\n")
    }

    private func needsCodingKeys(_ properties: [ObjectProperty]) -> Bool {
        properties.contains { property in
            unescaped(property.swiftName) != property.jsonKey
        }
    }

    private func unescaped(_ identifier: String) -> String {
        identifier.trimmingCharacters(in: CharacterSet(charactersIn: "`"))
    }

    private func renderAliasModel(_ model: ModelDefinition) -> String {
        let access = effectiveAccessPrefix
        let documentation = SwiftNaming.commentLines(
            model.schema["description"]?.stringValue ?? "Generated type for \(model.name)."
        )
        var type: String
        if model.isRecursive {
            usesJSONValue = true
            type = "JSONValue"
        } else {
            let resolved = resolveType(
                model.schema,
                hint: model.name,
                key: model.name + ".alias"
            )
            type = resolved.propertyType(optional: false)
        }
        return """
        \(documentation.joined(separator: "\n"))

        \(access)typealias \(model.name) = \(type)
        """
    }

    private func renderEnumModel(_ model: ModelDefinition) -> String {
        let access = effectiveAccessPrefix
        let values = enumValues(for: model.name)
        let rawType = model.kind == .stringEnum ? "String" : "Int"
        let documentation = SwiftNaming.commentLines(
            model.schema["description"]?.stringValue ?? "Generated enum for \(model.name)."
        )

        var caseNames: [String] = []
        var seenCaseNames: Set<String> = []
        var seenRawValues: Set<String> = []
        var lines: [String] = []
        let customNames = model.schema["x-enum-varnames"]?.stringArrayValue
            ?? model.schema["x-enumNames"]?.stringArrayValue

        for (index, value) in values.enumerated() {
            let rawValue: String
            if model.kind == .stringEnum {
                guard let string = value.stringValue else { continue }
                rawValue = string
            } else {
                guard let integer = value.int64Value, let intValue = Int(exactly: integer) else {
                    appendWarning(
                        "An integer enum value was outside the supported range and was skipped.",
                        context: model.name
                    )
                    continue
                }
                rawValue = String(intValue)
            }

            guard seenRawValues.insert(rawValue).inserted else {
                appendWarning(
                    "Duplicate enum value “\(rawValue)” was skipped in \(model.name).",
                    context: model.name
                )
                continue
            }

            var baseName: String
            if let customNames, customNames.indices.contains(index) {
                baseName = SwiftNaming.camel(customNames[index])
                if baseName.isEmpty {
                    baseName = SwiftNaming.camel(rawValue)
                }
            } else if model.kind == .stringEnum {
                baseName = SwiftNaming.camel(rawValue)
            } else {
                baseName = SwiftNaming.integerCase(value.int64Value ?? 0)
            }

            if baseName.isEmpty {
                baseName = "case\(index + 1)"
            }
            if baseName.first?.isNumber == true {
                baseName = "value" + baseName
            }

            var candidate = baseName
            var suffix = 2
            while seenCaseNames.contains(candidate) {
                candidate = baseName + String(suffix)
                suffix += 1
            }
            seenCaseNames.insert(candidate)
            caseNames.append(SwiftNaming.escape(candidate))

            if model.kind == .stringEnum {
                lines.append("case \(SwiftNaming.escape(candidate)) = \(SwiftNaming.stringLiteral(rawValue))")
            } else {
                lines.append("case \(SwiftNaming.escape(candidate)) = \(rawValue)")
            }
        }

        if lines.isEmpty {
            return renderAliasFallback(model, type: "JSONValue")
        }

        return """
        \(documentation.joined(separator: "\n"))

        \(access)enum \(model.name): \(rawType), Codable, CaseIterable {
        \(SwiftNaming.indent(lines.joined(separator: "\n")))
        }
        """
    }

    private func renderAliasFallback(_ model: ModelDefinition, type: String) -> String {
        usesJSONValue = true
        let access = effectiveAccessPrefix
        return """
        \(SwiftNaming.commentLines("Generated type for \(model.name).").joined(separator: "\n"))

        \(access)typealias \(model.name) = \(type)
        """
    }

    private struct UnionCase {
        var label: String
        var type: String
    }

    private func renderUnionModel(_ model: ModelDefinition) -> String {
        usesJSONValue = true
        let access = effectiveAccessPrefix
        let types = unionTypes(for: model.name)
        if types.isEmpty {
            return renderAliasFallback(model, type: "JSONValue")
        }

        var usedLabels: Set<String> = []
        var cases: [UnionCase] = []
        for (index, type) in types.enumerated() {
            var base = SwiftNaming.camel(
                type.swiftType
                    .replacingOccurrences(of: "[", with: " ")
                    .replacingOccurrences(of: "]", with: " ")
                    .replacingOccurrences(of: ":", with: " ")
                    .replacingOccurrences(of: "?", with: " ")
            )
            if base.isEmpty {
                base = "variant\(index + 1)"
            }
            if base.first?.isNumber == true {
                base = "value" + base
            }
            var candidate = base
            var suffix = 2
            while usedLabels.contains(candidate) {
                candidate = base + String(suffix)
                suffix += 1
            }
            usedLabels.insert(candidate)
            cases.append(UnionCase(
                label: SwiftNaming.escape(candidate),
                type: type.propertyType(optional: false)
            ))
        }

        var unknownBase = "unknown"
        var unknownSuffix = 2
        while usedLabels.contains(unescaped(unknownBase)) {
            unknownBase = "unknown\(unknownSuffix)"
            unknownSuffix += 1
        }
        let unknownLabel = SwiftNaming.escape(unknownBase)

        let documentation = SwiftNaming.commentLines(
            model.schema["description"]?.stringValue ?? "Generated union for \(model.name)."
        )
        var lines: [String] = []
        lines.append(documentation.joined(separator: "\n"))
        let indirect = model.isRecursive ? "indirect " : ""
        lines.append("\(access)\(indirect)enum \(model.name): Codable {")
        for unionCase in cases {
            lines.append("    case \(unionCase.label)(\(unionCase.type))")
        }
        lines.append("    case \(unknownLabel)(JSONValue)")
        lines.append("")
        lines.append("    \(access)init(from decoder: Decoder) throws {")
        lines.append("        let container = try decoder.singleValueContainer()")
        for unionCase in cases {
            lines.append("        if let value = try? container.decode(\(metatypeExpression(unionCase.type))) {")
            lines.append("            self = .\(unionCase.label)(value)")
            lines.append("            return")
            lines.append("        }")
        }
        lines.append("        self = .\(unknownLabel)(try container.decode(JSONValue.self))")
        lines.append("    }")
        lines.append("")
        lines.append("    \(access)func encode(to encoder: Encoder) throws {")
        lines.append("        var container = encoder.singleValueContainer()")
        lines.append("        switch self {")
        for unionCase in cases {
            lines.append("        case .\(unionCase.label)(let value):")
            lines.append("            try container.encode(value)")
        }
        lines.append("        case .\(unknownLabel)(let value):")
        lines.append("            try container.encode(value)")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        return lines.joined(separator: "\n")
    }

    private func renderAPIClientFile() -> String {
        let access = effectiveAccessPrefix
        let defaultURL = SwiftNaming.stringLiteral(baseURL)
        return #"""
        \#(generatedHeader)

        import Foundation

        \#(access)enum HTTPMethod: String, Sendable {
            case get = "GET"
            case post = "POST"
            case put = "PUT"
            case patch = "PATCH"
            case delete = "DELETE"
            case head = "HEAD"
            case options = "OPTIONS"
            case trace = "TRACE"
        }

        \#(access)enum APIError: LocalizedError, @unchecked Sendable {
            case invalidURL
            case invalidResponse
            case httpStatus(code: Int, data: Data)
            case decoding(Error)
            case encoding(Error)
            case emptyResponse
            case transport(Error)

            \#(access)var errorDescription: String? {
                switch self {
                case .invalidURL:
                    return "The request URL could not be created."
                case .invalidResponse:
                    return "The server returned an invalid response."
                case .httpStatus(let code, _):
                    return "The server returned HTTP \(code)."
                case .decoding(let error):
                    return "The response could not be decoded. \(error.localizedDescription)"
                case .encoding(let error):
                    return "The request could not be encoded. \(error.localizedDescription)"
                case .emptyResponse:
                    return "The server returned an empty response."
                case .transport(let error):
                    return "The request failed. \(error.localizedDescription)"
                }
            }

            \#(access)var responseBody: Data? {
                if case .httpStatus(_, let data) = self {
                    return data
                }
                return nil
            }
        }

        \#(access)struct EmptyResponse: Decodable, Sendable {
            \#(access)init() {}
        }

        \#(access)struct APIAuth: Sendable {
            \#(access)enum APIKeyLocation: Sendable {
                case header
                case query
            }

            \#(access)var bearerToken: String?
            \#(access)var apiKey: String?
            \#(access)var apiKeyName: String
            \#(access)var apiKeyLocation: APIKeyLocation
            \#(access)var basicUsername: String?
            \#(access)var basicPassword: String?
            \#(access)var additionalHeaders: [String: String]

            \#(access)init(
                bearerToken: String? = nil,
                apiKey: String? = nil,
                apiKeyName: String = "X-API-Key",
                apiKeyLocation: APIKeyLocation = .header,
                basicUsername: String? = nil,
                basicPassword: String? = nil,
                additionalHeaders: [String: String] = [:]
            ) {
                self.bearerToken = bearerToken
                self.apiKey = apiKey
                self.apiKeyName = apiKeyName
                self.apiKeyLocation = apiKeyLocation
                self.basicUsername = basicUsername
                self.basicPassword = basicPassword
                self.additionalHeaders = additionalHeaders
            }

            \#(access)static func bearer(_ token: String) -> APIAuth {
                APIAuth(bearerToken: token)
            }

            \#(access)static func apiKey(
                _ value: String,
                name: String = "X-API-Key",
                location: APIKeyLocation = .header
            ) -> APIAuth {
                APIAuth(apiKey: value, apiKeyName: name, apiKeyLocation: location)
            }

            \#(access)static func basic(username: String, password: String) -> APIAuth {
                APIAuth(basicUsername: username, basicPassword: password)
            }
        }

        \#(access)final class APIClient: @unchecked Sendable {
            \#(access)static let shared = APIClient()

            \#(access)var baseURL: URL
            \#(access)var auth: APIAuth?
            \#(access)var defaultHeaders: [String: String]

            private let session: URLSession

            \#(access)init(
                baseURL: URL,
                auth: APIAuth? = nil,
                session: URLSession = .shared,
                defaultHeaders: [String: String] = [:]
            ) {
                self.baseURL = baseURL
                self.auth = auth
                self.session = session
                self.defaultHeaders = defaultHeaders
            }

            \#(access)convenience init(auth: APIAuth? = nil) {
                self.init(baseURL: URL(string: \#(defaultURL))!, auth: auth)
            }

            private static let pathAllowed = CharacterSet.alphanumerics
                .union(CharacterSet(charactersIn: "-._~"))

            \#(access)static func pathComponent(_ value: String) -> String {
                value.addingPercentEncoding(withAllowedCharacters: pathAllowed) ?? value
            }

            \#(access)static func queryString(_ date: Date) -> String {
                let formatter = ISO8601DateFormatter()
                formatter.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
                return formatter.string(from: date)
            }

            private func makeURL(path: String, queryItems: [URLQueryItem]) throws -> URL {
                let root = baseURL.absoluteString
                    .trimmingCharacters(in: CharacterSet(charactersIn: "/"))
                let relative = path.hasPrefix("/") ? String(path.dropFirst()) : path
                guard var components = URLComponents(string: root + "/" + relative) else {
                    throw APIError.invalidURL
                }
                if !queryItems.isEmpty {
                    components.queryItems = (components.queryItems ?? []) + queryItems
                }
                guard let url = components.url else {
                    throw APIError.invalidURL
                }
                return url
            }

            private func execute(
                path: String,
                method: HTTPMethod,
                queryItems: [URLQueryItem],
                headers: [String: String],
                bodyData: Data?
            ) async throws -> Data {
                var allQueryItems = queryItems
                var allHeaders = defaultHeaders

                if let auth {
                    if let token = auth.bearerToken, !token.isEmpty {
                        allHeaders["Authorization"] = "Bearer \(token)"
                    }
                    if let key = auth.apiKey, !key.isEmpty {
                        switch auth.apiKeyLocation {
                        case .header:
                            allHeaders[auth.apiKeyName] = key
                        case .query:
                            allQueryItems.append(URLQueryItem(name: auth.apiKeyName, value: key))
                        }
                    }
                    if let username = auth.basicUsername, let password = auth.basicPassword {
                        let credentials = Data("\(username):\(password)".utf8).base64EncodedString()
                        allHeaders["Authorization"] = "Basic \(credentials)"
                    }
                    for (key, value) in auth.additionalHeaders {
                        allHeaders[key] = value
                    }
                }

                for (key, value) in headers {
                    allHeaders[key] = value
                }
                if allHeaders["Accept"] == nil {
                    allHeaders["Accept"] = "application/json"
                }
                if bodyData != nil, allHeaders["Content-Type"] == nil {
                    allHeaders["Content-Type"] = "application/json"
                }

                let url = try makeURL(path: path, queryItems: allQueryItems)
                var request = URLRequest(url: url)
                request.httpMethod = method.rawValue
                request.httpBody = bodyData
                request.timeoutInterval = 60
                for (key, value) in allHeaders {
                    request.setValue(value, forHTTPHeaderField: key)
                }

                let data: Data
                let response: URLResponse
                do {
                    (data, response) = try await session.data(for: request)
                } catch {
                    throw APIError.transport(error)
                }

                guard let http = response as? HTTPURLResponse else {
                    throw APIError.invalidResponse
                }
                guard (200..<300).contains(http.statusCode) else {
                    throw APIError.httpStatus(code: http.statusCode, data: data)
                }
                return data
            }

            private func encode<Body: Encodable>(_ body: Body?) throws -> Data? {
                guard let body else { return nil }
                do {
                    let encoder = JSONEncoder()
                    encoder.dateEncodingStrategy = .iso8601
                    return try encoder.encode(body)
                } catch {
                    throw APIError.encoding(error)
                }
            }

            private func decode<T: Decodable>(_ data: Data, as type: T.Type) throws -> T {
                guard !data.isEmpty else { throw APIError.emptyResponse }
                do {
                    return try Self.makeDecoder().decode(type, from: data)
                } catch {
                    throw APIError.decoding(error)
                }
            }

            private static func makeDecoder() -> JSONDecoder {
                let decoder = JSONDecoder()
                decoder.dateDecodingStrategy = .custom { decoder in
                    let container = try decoder.singleValueContainer()
                    let raw = try container.decode(String.self)

                    let iso = ISO8601DateFormatter()
                    iso.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
                    if let date = iso.date(from: raw) { return date }

                    iso.formatOptions = [.withInternetDateTime]
                    if let date = iso.date(from: raw) { return date }

                    let day = DateFormatter()
                    day.locale = Locale(identifier: "en_US_POSIX")
                    day.timeZone = TimeZone(secondsFromGMT: 0)
                    day.dateFormat = "yyyy-MM-dd"
                    if let date = day.date(from: raw) { return date }

                    throw DecodingError.dataCorruptedError(
                        in: container,
                        debugDescription: "Invalid ISO 8601 date: \(raw)"
                    )
                }
                return decoder
            }

            \#(access)func send<T: Decodable>(
                path: String,
                method: HTTPMethod,
                queryItems: [URLQueryItem] = [],
                headers: [String: String] = [:],
                responseType: T.Type
            ) async throws -> T {
                let data = try await execute(
                    path: path,
                    method: method,
                    queryItems: queryItems,
                    headers: headers,
                    bodyData: nil
                )
                return try decode(data, as: responseType)
            }

            \#(access)func send<Body: Encodable, T: Decodable>(
                path: String,
                method: HTTPMethod,
                queryItems: [URLQueryItem] = [],
                headers: [String: String] = [:],
                body: Body?,
                responseType: T.Type
            ) async throws -> T {
                let data = try await execute(
                    path: path,
                    method: method,
                    queryItems: queryItems,
                    headers: headers,
                    bodyData: try encode(body)
                )
                return try decode(data, as: responseType)
            }

            \#(access)func sendRaw(
                path: String,
                method: HTTPMethod,
                queryItems: [URLQueryItem] = [],
                headers: [String: String] = [:]
            ) async throws -> Data {
                try await execute(
                    path: path,
                    method: method,
                    queryItems: queryItems,
                    headers: headers,
                    bodyData: nil
                )
            }

            \#(access)func sendRaw<Body: Encodable>(
                path: String,
                method: HTTPMethod,
                queryItems: [URLQueryItem] = [],
                headers: [String: String] = [:],
                body: Body?
            ) async throws -> Data {
                try await execute(
                    path: path,
                    method: method,
                    queryItems: queryItems,
                    headers: headers,
                    bodyData: try encode(body)
                )
            }

            \#(access)func sendEmpty(
                path: String,
                method: HTTPMethod,
                queryItems: [URLQueryItem] = [],
                headers: [String: String] = [:]
            ) async throws {
                _ = try await execute(
                    path: path,
                    method: method,
                    queryItems: queryItems,
                    headers: headers,
                    bodyData: nil
                )
            }

            \#(access)func sendEmpty<Body: Encodable>(
                path: String,
                method: HTTPMethod,
                queryItems: [URLQueryItem] = [],
                headers: [String: String] = [:],
                body: Body?
            ) async throws {
                _ = try await execute(
                    path: path,
                    method: method,
                    queryItems: queryItems,
                    headers: headers,
                    bodyData: try encode(body)
                )
            }
        }
        """#
    }

    private func renderEndpointsFile() -> String {
        let access = effectiveAccessPrefix
        let methods = operations.map { renderEndpoint($0, access: access) }
        return """
        \(generatedHeader)

        import Foundation

        extension APIClient {
        \(SwiftNaming.indent(methods.joined(separator: "\n\n")))
        }
        """
    }

    private func renderEndpoint(_ operation: OperationDefinition, access: String) -> String {
        var lines: [String] = []
        var doc = SwiftNaming.commentLines(operation.summary)
        let signatureAndRoute = "\(operation.method) \(operation.path)"
        doc.append("///")
        doc.append("/// `\(signatureAndRoute)`")
        if let description = operation.description?.trimmingCharacters(in: .whitespacesAndNewlines),
           !description.isEmpty,
           description != operation.summary {
            doc.append("///")
            doc.append(contentsOf: SwiftNaming.commentLines(description))
        }

        let documentedParameters = operation.parameters.filter { $0.description?.isEmpty == false }
        if !documentedParameters.isEmpty || operation.body != nil {
            doc.append("///")
            doc.append("/// - Parameters:")
            for parameter in operation.parameters {
                guard let description = parameter.description, !description.isEmpty else { continue }
                doc.append("///   - \(parameter.swiftName): \(description.replacingOccurrences(of: "\n", with: " "))")
            }
            if operation.body != nil {
                doc.append("///   - \(operation.body!.swiftName): The JSON request body.")
            }
        }
        if operation.response.kind != .empty {
            doc.append("/// - Returns: \(operation.response.swiftTypeName).")
        }

        if operation.isDeprecated {
            lines.append("@available(*, deprecated, message: \"This endpoint is deprecated in the API specification.\")")
        }
        lines.append(contentsOf: doc)

        var signatureParts: [String] = []
        for parameter in operation.parameters {
            let optional = !parameter.isRequired
            let defaultValue = optional ? " = nil" : ""
            signatureParts.append(
                "\(parameter.swiftName): \(parameter.type.propertyType(optional: optional))\(defaultValue)"
            )
        }
        if let body = operation.body {
            let optional = !body.isRequired
            let defaultValue = optional ? " = nil" : ""
            signatureParts.append(
                "\(body.swiftName): \(body.type.propertyType(optional: optional))\(defaultValue)"
            )
        }
        let signature = signatureParts.joined(separator: ", ")
        lines.append("\(access)func \(operation.swiftName)(\(signature)) async throws -> \(operation.response.swiftTypeName) {")

        var bodyLines: [String] = []
        let pathParameters = operation.parameters.filter { $0.location == .path }
        let pathLiteral = renderPathLiteral(operation.path, parameters: pathParameters)
        bodyLines.append("let path = \(pathLiteral)")

        let queryParameters = operation.parameters.filter { $0.location == .query }
        if !queryParameters.isEmpty {
            bodyLines.append("")
            bodyLines.append("var queryItems: [URLQueryItem] = []")
            for parameter in queryParameters {
                bodyLines.append(contentsOf: renderQueryParameter(parameter))
            }
        }

        let headerParameters = operation.parameters.filter { $0.location == .header }
        let responseMediaType = operation.response.mediaType?.lowercased()
        let needsAcceptHeader: Bool
        switch operation.response.kind {
        case .text, .data:
            needsAcceptHeader = true
        case .json:
            needsAcceptHeader = responseMediaType != nil && responseMediaType != "application/json"
        case .empty:
            needsAcceptHeader = false
        }

        let bodyContentType: String?
        if let contentType = operation.body?.contentType,
           contentType.lowercased() != "application/json" {
            bodyContentType = contentType
        } else {
            bodyContentType = nil
        }

        let needsHeaders = !headerParameters.isEmpty || needsAcceptHeader || bodyContentType != nil
        if needsHeaders {
            bodyLines.append("")
            if needsAcceptHeader, let mediaType = operation.response.mediaType {
                bodyLines.append("var headers: [String: String] = [\"Accept\": \(SwiftNaming.stringLiteral(mediaType))]")
            } else {
                bodyLines.append("var headers: [String: String] = [:]")
            }
            if let bodyContentType {
                bodyLines.append("headers[\"Content-Type\"] = \(SwiftNaming.stringLiteral(bodyContentType))")
            }
            for parameter in headerParameters {
                bodyLines.append(contentsOf: renderHeaderParameter(parameter))
            }
        }

        bodyLines.append("")
        let callLines = renderNetworkCall(
            operation: operation,
            hasQueryItems: !queryParameters.isEmpty,
            hasHeaders: needsHeaders
        )
        bodyLines.append(contentsOf: callLines)
        lines.append(SwiftNaming.indent(bodyLines.joined(separator: "\n")))
        lines.append("}")
        return lines.joined(separator: "\n")
    }

    private func renderPathLiteral(_ path: String, parameters: [OperationParameter]) -> String {
        let lookup = Dictionary(uniqueKeysWithValues: parameters.map { ($0.jsonName, $0) })
        var result = "\""
        var index = path.startIndex
        while index < path.endIndex {
            let character = path[index]
            if character == "{" {
                if let end = path[index...].firstIndex(of: "}") {
                    let name = String(path[path.index(after: index)..<end])
                    if let parameter = lookup[name] {
                        let expression = pathExpression(parameter)
                        result += "\\(APIClient.pathComponent(\(expression)))"
                    } else {
                        result += "{" + name + "}"
                    }
                    index = path.index(after: end)
                    continue
                }
            }
            switch character {
            case "\\":
                result += "\\\\"
            case "\"":
                result += "\\\""
            default:
                result.append(character)
            }
            index = path.index(after: index)
        }
        result += "\""
        return result
    }

    private func pathExpression(_ parameter: OperationParameter) -> String {
        let name = parameter.swiftName
        switch parameter.type.scalar {
        case .enumString:
            return "\(name).rawValue"
        case .enumInt:
            return "String(\(name).rawValue)"
        case .date:
            return "APIClient.queryString(\(name))"
        case .data:
            return "\(name).base64EncodedString()"
        default:
            return "String(describing: \(name))"
        }
    }

    private func renderQueryParameter(_ parameter: OperationParameter) -> [String] {
        let name = parameter.swiftName
        let jsonName = SwiftNaming.stringLiteral(parameter.jsonName)
        let optional = !parameter.isRequired

        if parameter.type.isArray {
            if parameter.explode {
                let expression = "\(name).map { URLQueryItem(name: \(jsonName), value: \(arrayValueExpression("$0", scalar: parameter.type.arrayElementScalar))) }"
                if optional {
                    return [
                        "if let \(name) {",
                        "    queryItems.append(contentsOf: \(expression))",
                        "}"
                    ]
                }
                return ["queryItems.append(contentsOf: \(expression))"]
            }

            let joined = "\(name).map { \(arrayValueExpression("$0", scalar: parameter.type.arrayElementScalar)) }.joined(separator: \",\")"
            if optional {
                return [
                    "if let \(name) {",
                    "    queryItems.append(URLQueryItem(name: \(jsonName), value: \(joined)))",
                    "}"
                ]
            }
            return ["queryItems.append(URLQueryItem(name: \(jsonName), value: \(joined)))"]
        }

        let value = queryValueExpression(name, type: parameter.type)
        if optional {
            return [
                "if let \(name) {",
                "    queryItems.append(URLQueryItem(name: \(jsonName), value: \(value)))",
                "}"
            ]
        }
        return ["queryItems.append(URLQueryItem(name: \(jsonName), value: \(value)))"]
    }

    private func renderHeaderParameter(_ parameter: OperationParameter) -> [String] {
        let name = parameter.swiftName
        let headerName = SwiftNaming.stringLiteral(parameter.jsonName)
        let optional = !parameter.isRequired

        if parameter.type.isArray {
            let expression = "\(name).map { \(arrayValueExpression("$0", scalar: parameter.type.arrayElementScalar)) }.joined(separator: \",\")"
            if optional {
                return [
                    "if let \(name) {",
                    "    headers[\(headerName)] = \(expression)",
                    "}"
                ]
            }
            return ["headers[\(headerName)] = \(expression)"]
        }

        let value = queryValueExpression(name, type: parameter.type)
        if optional {
            return [
                "if let \(name) {",
                "    headers[\(headerName)] = \(value)",
                "}"
            ]
        }
        return ["headers[\(headerName)] = \(value)"]
    }

    private func queryValueExpression(_ name: String, type: ResolvedType) -> String {
        switch type.scalar {
        case .string:
            return name
        case .number:
            return "String(\(name))"
        case .boolean:
            return "\(name) ? \"true\" : \"false\""
        case .date:
            return "APIClient.queryString(\(name))"
        case .data:
            return "\(name).base64EncodedString()"
        case .enumString:
            return "\(name).rawValue"
        case .enumInt:
            return "String(\(name).rawValue)"
        case .object, .json, .none:
            return "String(describing: \(name))"
        }
    }

    private func arrayValueExpression(_ name: String, scalar: ResolvedType.ScalarKind?) -> String {
        switch scalar {
        case .string:
            return name
        case .number:
            return "String(\(name))"
        case .boolean:
            return "\(name) ? \"true\" : \"false\""
        case .date:
            return "APIClient.queryString(\(name))"
        case .data:
            return "\(name).base64EncodedString()"
        case .enumString:
            return "\(name).rawValue"
        case .enumInt:
            return "String(\(name).rawValue)"
        case .object, .json, .none:
            return "String(describing: \(name))"
        }
    }

    private func metatypeExpression(_ type: String) -> String {
        if type.hasSuffix("?") {
            return "Optional<\(type.dropLast())>.self"
        }
        return "\(type).self"
    }

    private func renderNetworkCall(
        operation: OperationDefinition,
        hasQueryItems: Bool,
        hasHeaders: Bool
    ) -> [String] {
        var arguments: [String] = [
            "path: path",
            "method: .\(operation.method.lowercased())"
        ]
        if hasQueryItems {
            arguments.append("queryItems: queryItems")
        }
        if hasHeaders {
            arguments.append("headers: headers")
        }
        if let body = operation.body {
            arguments.append("body: \(body.swiftName)")
        }

        let call: [String]
        switch operation.response.kind {
        case .json:
            arguments.append("responseType: \(metatypeExpression(operation.response.swiftTypeName))")
            call = ["return try await send(", SwiftNaming.indent(arguments.joined(separator: ",\n"), by: 4), ")"]
        case .text:
            call = [
                "let data = try await sendRaw(",
                SwiftNaming.indent(arguments.joined(separator: ",\n"), by: 4),
                ")",
                "return String(decoding: data, as: UTF8.self)"
            ]
        case .data:
            call = [
                "return try await sendRaw(",
                SwiftNaming.indent(arguments.joined(separator: ",\n"), by: 4),
                ")"
            ]
        case .empty:
            call = [
                "try await sendEmpty(",
                SwiftNaming.indent(arguments.joined(separator: ",\n"), by: 4),
                ")"
            ]
        }
        return call
    }

    private func renderJSONValueFile() -> String {
        let access = effectiveAccessPrefix
        return #"""
        \#(generatedHeader)

        import Foundation

        \#(access)enum JSONValue: Codable, Equatable, Sendable {
            case null
            case bool(Bool)
            case integer(Int64)
            case number(Double)
            case string(String)
            case array([JSONValue])
            case object([String: JSONValue])

            \#(access)init(from decoder: Decoder) throws {
                let container = try decoder.singleValueContainer()
                if container.decodeNil() {
                    self = .null
                } else if let value = try? container.decode(Bool.self) {
                    self = .bool(value)
                } else if let value = try? container.decode(Int64.self) {
                    self = .integer(value)
                } else if let value = try? container.decode(Double.self) {
                    self = .number(value)
                } else if let value = try? container.decode(String.self) {
                    self = .string(value)
                } else if let value = try? container.decode([JSONValue].self) {
                    self = .array(value)
                } else if let value = try? container.decode([String: JSONValue].self) {
                    self = .object(value)
                } else {
                    throw DecodingError.dataCorruptedError(
                        in: container,
                        debugDescription: "Unsupported JSON value"
                    )
                }
            }

            \#(access)func encode(to encoder: Encoder) throws {
                var container = encoder.singleValueContainer()
                switch self {
                case .null:
                    try container.encodeNil()
                case .bool(let value):
                    try container.encode(value)
                case .integer(let value):
                    try container.encode(value)
                case .number(let value):
                    try container.encode(value)
                case .string(let value):
                    try container.encode(value)
                case .array(let value):
                    try container.encode(value)
                case .object(let value):
                    try container.encode(value)
                }
            }
        }
        """#
    }

