        - `\(sourceRoot)APIClient.swift` — networking, auth, dates, and errors
        - `\(sourceRoot)Endpoints.swift` — one typed method per API operation
        - `\(sourceRoot)JSONValue.swift` — flexible JSON fallback when present

        ---

        Regenerate this client with SpecForge whenever the API contract changes.

        """
    }
