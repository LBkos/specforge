    private func renderReadme(sourceRoot: String) -> String {
        let access = effectiveAccessPrefix
        let packageImport = (options.accessLevel == .public && options.includePackageManifest)
            ? "import \(packageName)\n\n"
            : ""
        let endpointRows = operations.map { operation in
            "| `\(operation.method)` | `\(operation.path)` | `\(operation.swiftName)` | `\(operation.response.swiftTypeName)` |"
        }.joined(separator: "\n")
        let endpointSection = operations.isEmpty
            ? "No endpoints were defined in the specification."
            : """
            | Method | Path | Swift method | Returns |
            | --- | --- | --- | --- |
            \(endpointRows)
            """

        let firstCall: String
        if let operation = operations.first(where: { $0.parameters.isEmpty && $0.body == nil }) {
            firstCall = "let response = try await client.\(operation.swiftName)()"
        } else if let operation = operations.first {
            firstCall = "let response = try await client.\(operation.swiftName)(/* add arguments */)"
        } else {
            firstCall = "// Add endpoints to the specification, then regenerate."
        }

        let importNote = access.isEmpty
            ? "> These types use internal access. They can be copied into an app target, but they cannot be imported from another module."
            : "> These types use public access and can be imported as a Swift package."

        let sourcePaths = options.includePackageManifest
            ? "Open the folder as a Swift package in Xcode, or add `\(packageName)` as a local package dependency. The sources live in `\(sourceRoot)`."
            : "Drag the generated Swift files into your Xcode target."

        return """
        # \(apiTitle) — Swift Client

        Generated by **SpecForge** from \(specVersion.displayName).

        - **API version:** \(apiVersion)
        - **Base URL:** `\(baseURL)`
        - **Package:** `\(packageName)`
        - **Models:** \(modelOrder.count)
        - **Endpoints:** \(operations.count)

        \(importNote)

        ## Requirements

        - Swift 5.9 or later
        - iOS 15+, macOS 12+, tvOS 15+, or watchOS 8+

        ## Install

        \(sourcePaths)

        ## Create a client

        ```swift
        import Foundation
        \(packageImport)
        let client = APIClient(auth: .bearer("YOUR_TOKEN"))
        ```

        Configure authentication at runtime. Tokens and passwords are never written into the generated sources.

        ```swift
        // API key in a header
        let keyed = APIClient(
            auth: .apiKey("YOUR_KEY", name: "X-API-Key", location: .header)
        )

        // HTTP Basic
        let basic = APIClient(auth: .basic(username: "user", password: "secret"))
        ```

        ## Make a request

        ```swift
        do {
            \(firstCall)
            print(response)
        } catch {
            print(error.localizedDescription)
        }
        ```

